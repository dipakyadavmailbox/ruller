/**
 * Translate `key` for `localeCode`, interpolating {placeholders} from `vars`.
 * Missing keys fall back to English, then to the key itself so a typo shows
 * up in the page instead of rendering an empty element.
 */
export function t(localeCode, key, vars) {
  const dict = UI[localeCode] || UI[DEFAULT_LOCALE]
  let value = dict[key]
  if (value === undefined) value = UI[DEFAULT_LOCALE][key]
  if (value === undefined) return key
  if (!vars) return value
  return value.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  )
}

/** Bind t() to one locale so templates can call tt('nav.about'). */
export function useTranslations(localeCode) {
  return (key, vars) => t(localeCode, key, vars)
}
